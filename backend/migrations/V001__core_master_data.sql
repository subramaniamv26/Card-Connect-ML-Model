-- V001: master data (customers, devices, cards, merchants), FX reference and import history.
-- Oracle 19c compatible: identity columns, IS JSON checks, CHAR(1) Y/N flags. No 21c/23ai syntax.

CREATE TABLE import_batches (
    import_id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset            VARCHAR2(40)   NOT NULL,
    file_name          VARCHAR2(260)  NOT NULL,
    file_path          VARCHAR2(500),
    file_sha256        VARCHAR2(64),
    file_size_bytes    NUMBER(14),
    status             VARCHAR2(30)   DEFAULT 'RECEIVED' NOT NULL,
    rows_total         NUMBER(12)     DEFAULT 0 NOT NULL,
    rows_valid         NUMBER(12)     DEFAULT 0 NOT NULL,
    rows_rejected      NUMBER(12)     DEFAULT 0 NOT NULL,
    rows_inserted      NUMBER(12)     DEFAULT 0 NOT NULL,
    rows_updated       NUMBER(12)     DEFAULT 0 NOT NULL,
    rows_unchanged     NUMBER(12)     DEFAULT 0 NOT NULL,
    error_summary      CLOB,
    uploaded_by        VARCHAR2(60)   NOT NULL,
    created_at         TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    started_at         TIMESTAMP,
    finished_at        TIMESTAMP,
    CONSTRAINT ck_import_status CHECK (status IN ('RECEIVED','VALIDATING','LOADING','COMPLETED',
                                                 'COMPLETED_WITH_ERRORS','FAILED')),
    CONSTRAINT ck_import_errsum CHECK (error_summary IS NULL OR error_summary IS JSON)
);
CREATE INDEX ix_import_batches_created ON import_batches (created_at);
CREATE INDEX ix_import_batches_status ON import_batches (status);

CREATE TABLE import_rejections (
    rejection_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    import_id      NUMBER        NOT NULL,
    row_number     NUMBER(12)    NOT NULL,
    column_name    VARCHAR2(60),
    error_code     VARCHAR2(40)  NOT NULL,
    error_message  VARCHAR2(500) NOT NULL,
    raw_record     VARCHAR2(4000),
    CONSTRAINT fk_rej_import FOREIGN KEY (import_id) REFERENCES import_batches (import_id) ON DELETE CASCADE
);
CREATE INDEX ix_import_rejections_import ON import_rejections (import_id, row_number);

CREATE TABLE fx_rates (
    currency        VARCHAR2(3)    NOT NULL,
    rate_to_lkr     NUMBER(14,6)   NOT NULL,
    valid_from      DATE           NOT NULL,
    valid_to        DATE,
    source          VARCHAR2(200)  NOT NULL,
    CONSTRAINT pk_fx_rates PRIMARY KEY (currency, valid_from),
    CONSTRAINT ck_fx_rate_pos CHECK (rate_to_lkr > 0)
);
