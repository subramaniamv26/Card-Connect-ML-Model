CREATE TABLE customers (
    customer_id             VARCHAR2(20)  NOT NULL,
    customer_name           VARCHAR2(100) NOT NULL,
    nic_no                  VARCHAR2(12)  NOT NULL,
    customer_segment        VARCHAR2(30)  NOT NULL,
    customer_home_city      VARCHAR2(60)  NOT NULL,
    customer_home_district  VARCHAR2(40)  NOT NULL,
    customer_home_province  VARCHAR2(40)  NOT NULL,
    customer_tenure_months  NUMBER(4)     NOT NULL,
    number_of_cards         NUMBER(2)     NOT NULL,
    customer_contact_no     VARCHAR2(20),
    row_hash                VARCHAR2(32)  NOT NULL,
    import_id               NUMBER,
    created_at              TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at              TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_customers PRIMARY KEY (customer_id),
    CONSTRAINT uq_customers_nic UNIQUE (nic_no),
    CONSTRAINT ck_cust_tenure CHECK (customer_tenure_months >= 0)
);
CREATE INDEX ix_customers_district ON customers (customer_home_district);
CREATE INDEX ix_customers_segment ON customers (customer_segment);

-- A customer can own several devices over time; exactly one is flagged primary.
CREATE TABLE customer_devices (
    mobile_device_id  VARCHAR2(20) NOT NULL,
    customer_id       VARCHAR2(20) NOT NULL,
    device_type       VARCHAR2(20) NOT NULL,
    device_os         VARCHAR2(10) NOT NULL,
    is_primary        CHAR(1)      DEFAULT 'Y' NOT NULL,
    first_seen_at     TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
    last_seen_at      TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
    import_id         NUMBER,
    CONSTRAINT pk_customer_devices PRIMARY KEY (mobile_device_id),
    CONSTRAINT fk_device_customer FOREIGN KEY (customer_id) REFERENCES customers (customer_id),
    CONSTRAINT ck_device_primary CHECK (is_primary IN ('Y','N')),
    CONSTRAINT ck_device_type CHECK (device_type IN ('MOBILE_PHONE','TABLET')),
    CONSTRAINT ck_device_os CHECK (device_os IN ('ANDROID','IOS'))
);
CREATE INDEX ix_devices_customer ON customer_devices (customer_id);

CREATE TABLE cards (
    card_id          VARCHAR2(20) NOT NULL,
    customer_id      VARCHAR2(20) NOT NULL,
    card_network     VARCHAR2(12) NOT NULL,
    card_type        VARCHAR2(6)  NOT NULL,
    card_tier        VARCHAR2(12) NOT NULL,
    card_age_months  NUMBER(4)    NOT NULL,
    card_status      VARCHAR2(10) NOT NULL,
    row_hash         VARCHAR2(32) NOT NULL,
    import_id        NUMBER,
    created_at       TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at       TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_cards PRIMARY KEY (card_id),
    CONSTRAINT fk_cards_customer FOREIGN KEY (customer_id) REFERENCES customers (customer_id),
    CONSTRAINT uq_cards_card_customer UNIQUE (card_id, customer_id),
    CONSTRAINT ck_card_network CHECK (card_network IN ('VISA','MASTERCARD','AMEX')),
    CONSTRAINT ck_card_type CHECK (card_type IN ('CREDIT','DEBIT')),
    CONSTRAINT ck_card_status CHECK (card_status IN ('ACTIVE','INACTIVE','BLOCKED'))
);
CREATE INDEX ix_cards_customer ON cards (customer_id, card_status);

CREATE TABLE merchants (
    merchant_id               VARCHAR2(20)  NOT NULL,
    merchant_brand            VARCHAR2(100) NOT NULL,
    merchant_category         VARCHAR2(20)  NOT NULL,
    merchant_location         VARCHAR2(200) NOT NULL,
    merchant_city             VARCHAR2(60)  NOT NULL,
    merchant_district         VARCHAR2(40)  NOT NULL,
    merchant_province         VARCHAR2(40)  NOT NULL,
    merchant_email            VARCHAR2(120),
    merchant_contact_no       VARCHAR2(20),
    merchant_type             VARCHAR2(10)  NOT NULL,
    merchant_offer_supported  CHAR(3)       DEFAULT 'NO' NOT NULL,
    is_active                 CHAR(1)       DEFAULT 'Y' NOT NULL,
    row_hash                  VARCHAR2(32)  NOT NULL,
    import_id                 NUMBER,
    created_at                TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at                TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_merchants PRIMARY KEY (merchant_id),
    CONSTRAINT ck_merchant_type CHECK (merchant_type IN ('PHYSICAL','ONLINE','SERVICE')),
    CONSTRAINT ck_merchant_offer CHECK (merchant_offer_supported IN ('YES','NO')),
    CONSTRAINT ck_merchant_active CHECK (is_active IN ('Y','N'))
);
CREATE INDEX ix_merchants_brand ON merchants (merchant_brand);
CREATE INDEX ix_merchants_category ON merchants (merchant_category);
CREATE INDEX ix_merchants_district ON merchants (merchant_district);
