-- V004: model registry, training history, recommendation batches, bulk jobs, locks, users, audit.

CREATE TABLE app_users (
    user_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username       VARCHAR2(60)  NOT NULL,
    password_hash  VARCHAR2(100) NOT NULL,
    role           VARCHAR2(12)  NOT NULL,
    is_active      CHAR(1)       DEFAULT 'Y' NOT NULL,
    created_at     TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    last_login_at  TIMESTAMP,
    CONSTRAINT uq_app_users_username UNIQUE (username),
    CONSTRAINT ck_user_role CHECK (role IN ('ADMIN','ANALYST','READ_ONLY')),
    CONSTRAINT ck_user_active CHECK (is_active IN ('Y','N'))
);

CREATE TABLE audit_log (
    audit_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at  TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    username     VARCHAR2(60)  NOT NULL,
    role         VARCHAR2(12),
    action       VARCHAR2(60)  NOT NULL,
    entity_type  VARCHAR2(40),
    entity_id    VARCHAR2(100),
    outcome      VARCHAR2(10)  DEFAULT 'SUCCESS' NOT NULL,
    client_ip    VARCHAR2(45),
    details      CLOB,
    CONSTRAINT ck_audit_details CHECK (details IS NULL OR details IS JSON),
    CONSTRAINT ck_audit_outcome CHECK (outcome IN ('SUCCESS','DENIED','FAILED'))
);
CREATE INDEX ix_audit_occurred ON audit_log (occurred_at);
CREATE INDEX ix_audit_user ON audit_log (username, occurred_at);

-- Single-row-per-key state, e.g. CURRENT_BATCH_ID and ACTIVE_MODEL_VERSION.
CREATE TABLE app_state (
    state_key    VARCHAR2(60)  NOT NULL,
    state_value  VARCHAR2(400),
    updated_at   TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_app_state PRIMARY KEY (state_key)
);

-- Lease-based mutual exclusion shared by all worker replicas.
CREATE TABLE job_locks (
    lock_name    VARCHAR2(60)  NOT NULL,
    owner_id     VARCHAR2(100),
    acquired_at  TIMESTAMP,
    expires_at   TIMESTAMP,
    CONSTRAINT pk_job_locks PRIMARY KEY (lock_name)
);
INSERT INTO job_locks (lock_name) VALUES ('TRAINING');
INSERT INTO job_locks (lock_name) VALUES ('BULK_JOBS');
INSERT INTO job_locks (lock_name) VALUES ('IMPORTS');

CREATE TABLE model_training_runs (
    run_id               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trigger_type         VARCHAR2(10)  NOT NULL,
    requested_by         VARCHAR2(60)  NOT NULL,
    status               VARCHAR2(12)  DEFAULT 'QUEUED' NOT NULL,
    attempt              NUMBER(3)     DEFAULT 0 NOT NULL,
    max_attempts         NUMBER(3)     DEFAULT 3 NOT NULL,
    model_version        VARCHAR2(40),
    algorithm            VARCHAR2(100),
    data_cutoff          DATE,
    window_start         DATE,
    window_end           DATE,
    transaction_rows     NUMBER(12),
    label_rows           NUMBER(12),
    metrics              CLOB,
    baseline_metrics     CLOB,
    active_model_metrics CLOB,
    promoted             CHAR(1)       DEFAULT 'N' NOT NULL,
    promotion_decision   VARCHAR2(1000),
    batch_id             NUMBER,
    error_message        VARCHAR2(4000),
    created_at           TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    started_at           TIMESTAMP,
    finished_at          TIMESTAMP,
    duration_seconds     NUMBER(10,1),
    CONSTRAINT ck_run_trigger CHECK (trigger_type IN ('SCHEDULED','MANUAL')),
    CONSTRAINT ck_run_status CHECK (status IN ('QUEUED','RUNNING','SUCCEEDED','REJECTED','FAILED','SKIPPED')),
    CONSTRAINT ck_run_promoted CHECK (promoted IN ('Y','N')),
    CONSTRAINT ck_run_metrics CHECK (metrics IS NULL OR metrics IS JSON),
    CONSTRAINT ck_run_bmetrics CHECK (baseline_metrics IS NULL OR baseline_metrics IS JSON),
    CONSTRAINT ck_run_ametrics CHECK (active_model_metrics IS NULL OR active_model_metrics IS JSON)
);
CREATE INDEX ix_runs_status ON model_training_runs (status, created_at);

CREATE TABLE model_registry (
    model_version    VARCHAR2(40)  NOT NULL,
    run_id           NUMBER        NOT NULL,
    algorithm        VARCHAR2(100) NOT NULL,
    status           VARCHAR2(10)  NOT NULL,
    artifact_path    VARCHAR2(500) NOT NULL,
    artifact_sha256  VARCHAR2(64)  NOT NULL,
    data_cutoff      DATE          NOT NULL,
    metrics          CLOB,
    created_at       TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    promoted_at      TIMESTAMP,
    retired_at       TIMESTAMP,
    CONSTRAINT pk_model_registry PRIMARY KEY (model_version),
    CONSTRAINT fk_registry_run FOREIGN KEY (run_id) REFERENCES model_training_runs (run_id),
    CONSTRAINT ck_registry_status CHECK (status IN ('CANDIDATE','ACTIVE','RETIRED','REJECTED')),
    CONSTRAINT ck_registry_metrics CHECK (metrics IS NULL OR metrics IS JSON)
);

CREATE TABLE recommendation_batches (
    batch_id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id              NUMBER,
    model_version       VARCHAR2(40)  NOT NULL,
    status              VARCHAR2(12)  DEFAULT 'BUILDING' NOT NULL,
    generated_at        TIMESTAMP     NOT NULL,
    data_as_of          DATE          NOT NULL,
    aggregation_start   DATE          NOT NULL,
    aggregation_end     DATE          NOT NULL,
    customer_count      NUMBER(10)    DEFAULT 0 NOT NULL,
    recommendation_rows NUMBER(12)    DEFAULT 0 NOT NULL,
    customers_full      NUMBER(10)    DEFAULT 0 NOT NULL,
    customers_partial   NUMBER(10)    DEFAULT 0 NOT NULL,
    customers_none      NUMBER(10)    DEFAULT 0 NOT NULL,
    published_at        TIMESTAMP,
    CONSTRAINT ck_batch_status CHECK (status IN ('BUILDING','PUBLISHED','SUPERSEDED','FAILED'))
);

-- Up to RESERVE_DEPTH ranked candidates per customer are stored; the API serves the first three that
-- are still eligible at request time, so a revoked offer is replaced without retraining.
CREATE TABLE customer_recommendations (
    batch_id                         NUMBER        NOT NULL,
    customer_id                      VARCHAR2(20)  NOT NULL,
    candidate_rank                   NUMBER(2)     NOT NULL,
    offer_id                         VARCHAR2(30)  NOT NULL,
    card_id                          VARCHAR2(20)  NOT NULL,
    merchant_id                      VARCHAR2(20)  NOT NULL,
    recommendation_score             NUMBER(10,6)  NOT NULL,
    relevance_score                  NUMBER(10,6),
    recommendation_reason            VARCHAR2(500) NOT NULL,
    reason_codes                     VARCHAR2(200),
    estimated_customer_saving        NUMBER(14,2),
    saving_assumption                VARCHAR2(400),
    merchant_txn_amount_3m           NUMBER(16,2)  NOT NULL,
    merchant_txn_count_3m            NUMBER(10)    NOT NULL,
    last_txn_date_with_merchant      DATE,
    avg_txn_amount_with_merchant     NUMBER(16,2),
    CONSTRAINT pk_customer_recs PRIMARY KEY (batch_id, customer_id, candidate_rank),
    CONSTRAINT fk_recs_batch FOREIGN KEY (batch_id) REFERENCES recommendation_batches (batch_id) ON DELETE CASCADE
);

CREATE TABLE customer_rec_status (
    batch_id          NUMBER        NOT NULL,
    customer_id       VARCHAR2(20)  NOT NULL,
    status            VARCHAR2(12)  NOT NULL,
    shortfall_reason  VARCHAR2(500),
    history_level     VARCHAR2(12)  NOT NULL,
    CONSTRAINT pk_customer_rec_status PRIMARY KEY (batch_id, customer_id),
    CONSTRAINT fk_rec_status_batch FOREIGN KEY (batch_id) REFERENCES recommendation_batches (batch_id) ON DELETE CASCADE,
    CONSTRAINT ck_rec_status CHECK (status IN ('FULL','PARTIAL','NONE')),
    CONSTRAINT ck_rec_history CHECK (history_level IN ('NONE','LIMITED','ESTABLISHED'))
);
CREATE INDEX ix_rec_status_status ON customer_rec_status (batch_id, status);

CREATE TABLE bulk_jobs (
    job_id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_type       VARCHAR2(30)  NOT NULL,
    status         VARCHAR2(12)  DEFAULT 'QUEUED' NOT NULL,
    parameters     CLOB,
    requested_by   VARCHAR2(60)  NOT NULL,
    requested_role VARCHAR2(12)  NOT NULL,
    include_pii    CHAR(1)       DEFAULT 'N' NOT NULL,
    batch_id       NUMBER,
    progress_pct   NUMBER(5,1)   DEFAULT 0 NOT NULL,
    row_count      NUMBER(12),
    result_path    VARCHAR2(500),
    result_sha256  VARCHAR2(64),
    error_message  VARCHAR2(4000),
    created_at     TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    started_at     TIMESTAMP,
    finished_at    TIMESTAMP,
    expires_at     TIMESTAMP,
    CONSTRAINT ck_job_type CHECK (job_type IN ('RECOMMENDATION_EXPORT','RECOMMENDATION_REFRESH')),
    CONSTRAINT ck_job_status CHECK (status IN ('QUEUED','RUNNING','SUCCEEDED','FAILED','EXPIRED')),
    CONSTRAINT ck_job_params CHECK (parameters IS NULL OR parameters IS JSON),
    CONSTRAINT ck_job_pii CHECK (include_pii IN ('Y','N'))
);
CREATE INDEX ix_bulk_jobs_status ON bulk_jobs (status, created_at);
