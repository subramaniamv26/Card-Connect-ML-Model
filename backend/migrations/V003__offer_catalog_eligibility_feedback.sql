-- V003: approved offer catalog, eligibility rules, engagement feedback, consent-aware delivery.

CREATE TABLE offers (
    offer_id                       VARCHAR2(30)   NOT NULL,
    offer_title                    VARCHAR2(150)  NOT NULL,
    offer_description              VARCHAR2(1000) NOT NULL,
    merchant_brand                 VARCHAR2(100),            -- brand-wide offer (all outlets)
    merchant_id                    VARCHAR2(20),             -- single-outlet offer
    merchant_category              VARCHAR2(20)   NOT NULL,
    offer_type                     VARCHAR2(20)   NOT NULL,
    offer_value                    NUMBER(12,2)   NOT NULL,
    currency                       VARCHAR2(3)    DEFAULT 'LKR' NOT NULL,
    minimum_spend                  NUMBER(14,2)   DEFAULT 0 NOT NULL,
    maximum_benefit                NUMBER(14,2),
    valid_from                     DATE           NOT NULL,
    valid_to                       DATE           NOT NULL,
    eligible_card_networks         VARCHAR2(100)  DEFAULT 'ALL' NOT NULL,
    eligible_card_types            VARCHAR2(30)   DEFAULT 'ALL' NOT NULL,
    eligible_card_tiers            VARCHAR2(100)  DEFAULT 'ALL' NOT NULL,
    eligible_locations             VARCHAR2(1000) DEFAULT 'ALL' NOT NULL,
    redemption_limit_per_customer  NUMBER(6),
    total_redemption_limit         NUMBER(10),
    campaign_budget                NUMBER(16,2),
    budget_consumed                NUMBER(16,2)   DEFAULT 0 NOT NULL,
    terms_and_conditions           CLOB           NOT NULL,
    status                         VARCHAR2(20)   DEFAULT 'PENDING_APPROVAL' NOT NULL,
    is_sample                      CHAR(1)        DEFAULT 'N' NOT NULL,
    revoked_reason                 VARCHAR2(400),
    version                        NUMBER(10)     DEFAULT 1 NOT NULL,
    created_by                     VARCHAR2(60)   NOT NULL,
    created_at                     TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    updated_by                     VARCHAR2(60),
    updated_at                     TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    approved_by                    VARCHAR2(60),
    approved_at                    TIMESTAMP,
    import_id                      NUMBER,
    CONSTRAINT pk_offers PRIMARY KEY (offer_id),
    CONSTRAINT fk_offers_merchant FOREIGN KEY (merchant_id) REFERENCES merchants (merchant_id),
    CONSTRAINT ck_offer_type CHECK (offer_type IN ('PERCENT_DISCOUNT','PERCENT_CASHBACK',
                                                  'FIXED_DISCOUNT','FIXED_CASHBACK')),
    CONSTRAINT ck_offer_value CHECK (offer_value > 0 AND
        (offer_type NOT IN ('PERCENT_DISCOUNT','PERCENT_CASHBACK') OR offer_value <= 100)),
    CONSTRAINT ck_offer_dates CHECK (valid_to >= valid_from),
    CONSTRAINT ck_offer_minspend CHECK (minimum_spend >= 0),
    CONSTRAINT ck_offer_maxben CHECK (maximum_benefit IS NULL OR maximum_benefit > 0),
    CONSTRAINT ck_offer_status CHECK (status IN ('DRAFT','PENDING_APPROVAL','APPROVED','SUSPENDED',
                                                'REVOKED','EXPIRED')),
    CONSTRAINT ck_offer_sample CHECK (is_sample IN ('Y','N')),
    CONSTRAINT ck_offer_target CHECK (merchant_brand IS NOT NULL OR merchant_id IS NOT NULL),
    CONSTRAINT ck_offer_approval CHECK (status <> 'APPROVED' OR approved_by IS NOT NULL)
);
CREATE INDEX ix_offers_status_validity ON offers (status, valid_from, valid_to);
CREATE INDEX ix_offers_brand ON offers (merchant_brand);

CREATE TABLE offer_eligibility_rules (
    rule_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    offer_id     VARCHAR2(30)  NOT NULL,
    rule_type    VARCHAR2(30)  NOT NULL,
    operator     VARCHAR2(10)  NOT NULL,
    rule_value   VARCHAR2(400),
    description  VARCHAR2(400),
    is_active    CHAR(1)       DEFAULT 'Y' NOT NULL,
    created_by   VARCHAR2(60)  NOT NULL,
    created_at   TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_rule_offer FOREIGN KEY (offer_id) REFERENCES offers (offer_id) ON DELETE CASCADE,
    CONSTRAINT ck_rule_type CHECK (rule_type IN ('CARD_NETWORK','CARD_TYPE','CARD_TIER','CUSTOMER_SEGMENT',
        'HOME_DISTRICT','HOME_PROVINCE','MIN_TENURE_MONTHS','MIN_SPEND_LAST_90D_LKR','NEW_TO_BRAND',
        'EXISTING_BRAND_CUSTOMER')),
    CONSTRAINT ck_rule_operator CHECK (operator IN ('IN','NOT_IN','GTE','LTE','IS_TRUE')),
    CONSTRAINT ck_rule_active CHECK (is_active IN ('Y','N'))
);
CREATE INDEX ix_rules_offer ON offer_eligibility_rules (offer_id, is_active);

CREATE TABLE offer_events (
    event_id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type       VARCHAR2(12)  NOT NULL,
    customer_id      VARCHAR2(20)  NOT NULL,
    offer_id         VARCHAR2(30)  NOT NULL,
    batch_id         NUMBER,
    card_id          VARCHAR2(20),
    transaction_id   VARCHAR2(20),
    channel          VARCHAR2(20),
    benefit_amount   NUMBER(14,2),
    occurred_at      TIMESTAMP     NOT NULL,
    recorded_at      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    recorded_by      VARCHAR2(60)  NOT NULL,
    idempotency_key  VARCHAR2(80)  NOT NULL,
    CONSTRAINT uq_offer_events_idem UNIQUE (idempotency_key),
    CONSTRAINT fk_event_customer FOREIGN KEY (customer_id) REFERENCES customers (customer_id),
    CONSTRAINT fk_event_offer FOREIGN KEY (offer_id) REFERENCES offers (offer_id),
    CONSTRAINT ck_event_type CHECK (event_type IN ('IMPRESSION','CLICK','REDEMPTION','DISMISSAL')),
    CONSTRAINT ck_event_benefit CHECK (benefit_amount IS NULL OR benefit_amount >= 0)
);
CREATE INDEX ix_events_customer_offer ON offer_events (customer_id, offer_id, event_type);
CREATE INDEX ix_events_offer_type ON offer_events (offer_id, event_type);
CREATE INDEX ix_events_occurred ON offer_events (occurred_at);

CREATE TABLE customer_channel_consents (
    customer_id     VARCHAR2(20)  NOT NULL,
    channel         VARCHAR2(10)  NOT NULL,
    consent_status  VARCHAR2(10)  NOT NULL,
    source          VARCHAR2(100) NOT NULL,
    updated_by      VARCHAR2(60)  NOT NULL,
    updated_at      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_consents PRIMARY KEY (customer_id, channel),
    CONSTRAINT fk_consent_customer FOREIGN KEY (customer_id) REFERENCES customers (customer_id),
    CONSTRAINT ck_consent_channel CHECK (channel IN ('SMS','PUSH','EMAIL')),
    CONSTRAINT ck_consent_status CHECK (consent_status IN ('GRANTED','WITHDRAWN'))
);

-- Integration point for an authorised delivery channel. Recommendation generation never writes here;
-- rows are created only through the explicit delivery API and only with recorded consent.
CREATE TABLE delivery_requests (
    delivery_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id    VARCHAR2(20)  NOT NULL,
    offer_id       VARCHAR2(30)  NOT NULL,
    batch_id       NUMBER,
    channel        VARCHAR2(10)  NOT NULL,
    status         VARCHAR2(20)  NOT NULL,
    status_reason  VARCHAR2(400),
    requested_by   VARCHAR2(60)  NOT NULL,
    created_at     TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at     TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_delivery_customer FOREIGN KEY (customer_id) REFERENCES customers (customer_id),
    CONSTRAINT fk_delivery_offer FOREIGN KEY (offer_id) REFERENCES offers (offer_id),
    CONSTRAINT ck_delivery_channel CHECK (channel IN ('SMS','PUSH','EMAIL')),
    CONSTRAINT ck_delivery_status CHECK (status IN ('BLOCKED_NO_CONSENT','BLOCKED_INELIGIBLE','QUEUED',
                                                   'HANDED_OFF','FAILED'))
);
CREATE INDEX ix_delivery_status ON delivery_requests (status, created_at);
